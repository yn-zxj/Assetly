const _fluentPrefix = 'fluent:';

String itemIconValue(String slug) => '$_fluentPrefix$slug';

String? itemIconSlug(String value) {
  if (value.startsWith(_fluentPrefix)) {
    final slug = value.substring(_fluentPrefix.length);
    return slug.isEmpty ? null : slug;
  }
  return _legacyEmoji[value];
}

String itemIconAsset(String slug) => 'assets/icons3d/$slug.webp';

final _glyphBySlug = <String, String>{
  for (final spec in itemIconSpecs) spec.slug: spec.glyph,
};

/// Plain-text icon for places that cannot draw an image, such as the printed
/// storage sticker and share text.
String itemIconGlyph(String value) {
  if (!value.startsWith(_fluentPrefix)) return value;
  return _glyphBySlug[value.substring(_fluentPrefix.length)] ?? '📦';
}

List<IconSpec> searchItemIcons(String query, {String category = 'all'}) {
  final q = query.trim().toLowerCase();
  return itemIconSpecs
      .where((spec) {
        if (category != 'all' && spec.category != category) return false;
        if (q.isEmpty) return true;
        return spec.label.contains(q) ||
            spec.slug.contains(q) ||
            spec.keywords.contains(q);
      })
      .toList(growable: false);
}
